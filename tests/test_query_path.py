def fixture_response():
    # Generated by the .NET Framework smoke executable, not a Python DTO factory.
    return wire.decode_envelope(
        (Path(__file__).parent / "fixtures/query_result_v2.json").read_bytes(),
        direction=wire.Direction.MOD_TO_PLUGIN,
        authenticated=True,
    )


def test_actual_csharp_json_keeps_new_nested_fields():
    response = fixture_response()
    values = response.payload.data["maps"][0]["new_field"]
    assert values == {"nullable": None, "values": [True, 0.875, "2026-09-05"]}
    assert wire.decode_envelope(wire.serialize_envelope(response)) == response


@pytest.mark.parametrize(
    "mutation",
    [
        lambda raw: raw.update(v=1),
        lambda raw: raw["payload"].update(extra=True),
        lambda raw: raw["payload"].update(status="partial", issues=[]),
        lambda raw: raw["payload"].update(issues=[{"code": "missing", "path": [True]}]),
        lambda raw: raw["payload"].update(data={"value": float("inf")}),
    ],
)
def test_generic_protocol_still_rejects_invalid_envelopes(mutation):
    raw = fixture_response().to_dict()
    mutation(raw)
    with pytest.raises(wire.ProtocolError):
        wire.decode_envelope(json.dumps(raw).encode())


def test_generic_arguments_are_detached_and_bounded():
    response = fixture_response()
    arguments = {"future_filter": {"values": [None, "alpha"]}}
    request = wire.make_query_request(
        response.connection_epoch, 5, response.session, "5" * 32, "future_operation", arguments
    )
    detached = request.to_dict()
    detached["payload"]["arguments"]["future_filter"]["values"].append("changed")
    assert arguments["future_filter"]["values"] == [None, "alpha"]
    deeply_nested = {}
    cursor = deeply_nested
    for _ in range(wire.MAX_JSON_DEPTH + 1):
        cursor["next"] = {}
        cursor = cursor["next"]
    with pytest.raises(wire.ProtocolError):
        wire.make_query_request(response.connection_epoch, 5, response.session, "5" * 32, "x", deeply_nested)


@pytest.mark.asyncio
async def test_arbitrary_tool_and_multiple_observations_survive_model_and_audit():
    response = fixture_response()
    response.payload.data["future_list"] = [{"id": i, "value": None} for i in range(700)]
    # Legal nested data must survive the additional observation/tool/audit wrappers.
    nested = {"value": "deep leaf"}
    for _ in range(26):
        nested = {"child": nested}
    response.payload.data["nested"] = nested
    response = wire.decode_envelope(wire.serialize_envelope(response))
    first = Observation.from_response("future_operation", {"filter": [1, 2]}, response)
    second = copy.deepcopy(first)
    second.value["response"]["load_epoch"] = "9" * 32
    observations = [first, second]
    registry = AgentAuditRegistry()

    async def handler(_args):
        return observations.pop(0)

    class Model:
        calls = 0

        async def complete(self, messages, tools, *, timeout):
            self.calls += 1
            if self.calls <= 2:
                return AssistantTurn("r", "m", "tool_calls", "", (ToolCall(str(self.calls), "future_reader", "{}"),))
            tool_messages = [m for m in messages if m["role"] == "tool"]
            assert len(tool_messages) == 2
            for message in tool_messages:
                value = json.loads(message["content"])["data"]["response"]["payload"]["data"]
                assert value["future_list"][-1] == {"id": 699, "value": None}
                assert value["nested"] == nested
            return AssistantTurn("r", "m", "tool_calls", "", (ToolCall("submit", "submit_response", json.dumps({"answer": "The requested observation is available."})),))

    runtime = AgentRuntime(
        observation_tools=[ToolSpec("future_reader", "test", {"type": "object"}, handler)],
        audit_registry=registry,
        logger=FakeLogger(),
        model_factory=lambda _: Model(),
    )
    result = await runtime.run("Inspect the requested data", settings())
    assert result["status"] == "ok"
    assert len(result["observations"]) == 2
    assert result["observations"][0]["response"]["load_epoch"] != result["observations"][1]["response"]["load_epoch"]
    events = registry.snapshot()["latest_run"]["events"]
    completed = [e for e in events if e["event"] == "tool_completed"]
    assert completed[0]["data"]["result"]["data"]["response"]["payload"]["data"]["future_list"][-1] == {
        "id": 699,
        "value": None,
    }
    assert "future_list" not in result["summary"]
    assert completed[0]["data"]["result"]["data"]["response"]["payload"]["data"]["nested"] == nested


def test_audit_depth_remains_bounded():
    nested = "leaf"
    for _ in range(MAX_AUDIT_DEPTH + 1):
        nested = {"child": nested}
    safe = audit_safe(nested)
    for _ in range(MAX_AUDIT_DEPTH):
        safe = safe["child"]
    assert safe == "<depth-limit>"


@pytest.mark.asyncio
async def test_plugin_tool_passes_operation_and_response_without_projection():
    response = fixture_response()

    class Bridge:
        def request(self, operation, arguments, timeout):
            assert operation == "future_operation" and arguments == {"id": "x"}
            return response

    plugin = object.__new__(NekoRimworldPlugin)
    plugin._bridge = Bridge()
    observation = await plugin._agent_query_tool({"operation": "future_operation", "arguments": {"id": "x"}})
    assert observation.value["response"] == response.to_dict()
    with pytest.raises(ToolExecutionError):
        await plugin._agent_query_tool({"operation": "x", "arguments": []})


@pytest.mark.asyncio
async def test_failed_query_retains_session_and_error_as_observation():
    from plugin.plugins.neko_rimworld.agent.tools import ToolRegistry

    response = fixture_response()
    raw = response.to_dict()
    raw["payload"] = {
        "status": "unsupported",
        "issues": [],
        "error_code": "unsupported_operation",
        "message": "Unknown operation.",
    }
    failed = wire.decode_envelope(json.dumps(raw).encode())

    async def handler(_):
        return Observation.from_response("new_operation", {}, failed)

    registry = ToolRegistry()
    registry.register(ToolSpec("reader", "test", {"type": "object"}, handler))
    result = await registry.execute(registry.prepare(ToolCall("r", "reader", "{}")))
    assert not result.ok
    assert result.value["error"]["code"] == "unsupported_operation"
    assert result.observation["response"]["load_epoch"] == failed.load_epoch
